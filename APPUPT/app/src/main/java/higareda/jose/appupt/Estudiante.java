package higareda.jose.appupt;

public class Estudiante {

    String id;
    String nombre;
    String carrera;
    String estado;
    String foto;

    public Estudiante(String id, String nombre, String carrera, String estado, String foto) {
        this.id = id;
        this.nombre = nombre;
        this.carrera = carrera;
        this.estado = estado;
        this.foto = foto;
    }

}